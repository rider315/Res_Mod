/** Provider-specific follow-up advice when the model's JSON can't be parsed. */
function invalidJsonHint(provider: AIProvider, model?: string): string {
  if (provider === 'cerebras')
    return 'Cerebras free-tier models may struggle with large prompts — try OpenRouter or Gemini instead.'
  if (provider === 'openrouter')
    return `The model${model ? ` "${model}"` : ''} may not follow JSON instructions well — pick another model in Settings (the recommended free ones support JSON mode).`
  return 'Please try again.'
}


function buildPrompt(
  resume: ParsedResume,
  jobDescription: string,
  hardInstructions: string,
  softInstructions: string
): string {
  // Build resume text with section IDs so Gemini can reference them accurately
  const resumeText = resume.sections
    .map((s) => `### ${s.title} [id: ${s.id}]\n${s.content.join('\n')}`)
    .join('\n\n')


  return `## RESUME TO OPTIMIZE
${resumeText}


## TARGET JOB DESCRIPTION
${jobDescription}


## HARD CONSTRAINTS — You MUST obey these exactly:
${hardInstructions || 'None'}


## SOFT GUIDELINES — Apply where appropriate:
${softInstructions || 'Use strong action verbs. Quantify achievements where possible. DIRECTLY USE the JD exact keywords in bullet points. Replace generic terms with JD-specific terminology.'}

## ATS-FIRST REWRITING STRATEGY (CRITICAL — THIS IS THE CORE PURPOSE)
The ENTIRE GOAL of this optimization is to PASS ATS keyword screening. Apply these rules:

### For Work Experience (EVERY role, no exceptions):
- Pick at least 2 bullet points per role and COMPLETELY REWRITE them using the JD's exact keywords.
- Do NOT just add a keyword at the end — restructure the entire sentence around the JD's terminology.
- Replace generic verbs and nouns with JD-specific ones (e.g., "worked on backend" → "designed and deployed microservices-based backend architecture").
- If the JD mentions specific tools (Docker, Kubernetes, Jenkins, etc.), the rewritten bullet MUST name those tools explicitly.
- If the JD mentions methodologies (Agile, Scrum, TDD, CI/CD), weave them into the bullet naturally.
- Preserve the original metric/achievement but completely reframe the approach using JD language.

### For Projects (EVERY project):
- Same aggressive rewriting as work experience — at least 1-2 bullets per project rewritten with JD keywords.
- The project description should read as if the candidate used exactly the tech stack the JD requires.

### For Skills:
- Swap out skills the JD doesn't care about for skills the JD explicitly requires.
- If the JD lists 10 required skills and the resume only has 4 of them, add the missing 6 by replacing the least relevant existing skills.

## CRITICAL LENGTH RULE
For every change, the "proposed" text MUST have the EXACT same character count as the "original" text (±5 chars max).
Count carefully. If original is 120 characters, proposed must be 115-125 characters.
This is non-negotiable — the document formatting will break otherwise.


## OUTPUT FORMAT
Return this exact JSON structure:
{
  "summary": "One paragraph describing what was optimized and why",
  "companyName": "The company name extracted from the job description (e.g. Google, Amazon, KPIT). If not found, use 'Company'",
  "keywordsAdded": ["keyword1", "keyword2"],
  "sectionsModified": ["Section Title 1", "Section Title 2"],
  "changes": [
    {
      "sectionId": "exact section id from the resume (e.g. section_0, section_1)",
      "sectionTitle": "Section Title",
      "original": "exact verbatim text from resume — must be findable via string search, character-for-character",
      "proposed": "improved plain-text replacement (MUST be within ±3 chars of original length, NO markdown, NO asterisks)",
      "reason": "why this change improves the resume for this specific role",
      "type": "rewrite|add_keywords|improve_clarity|action_verb"
    }
  ]
}


## SECTION SKIP LIST
Do NOT generate any changes for sections whose title contains any of these (case-insensitive):
- "Education"
- "Award"
- "Certificate"
- "Header"
- "Contact"

## RULES
- Suggest 10 to 20 high-impact changes — be thorough, cover every experience and project
- "original" must EXACTLY match text that exists in the resume — no paraphrasing, no trimming
- NEVER touch frozen fields (company names, role titles, dates, project names)
- Maintain the same character length (±5 chars) for every proposed change
- EVERY work experience role MUST have at least 2 bullet point changes
- EVERY project MUST have at least 1 bullet point change

## ATS KEYWORD OPTIMIZATION (CRITICAL FOR PASSING AUTOMATED SCREENING)
Before generating changes, perform this analysis:

### Step 1: Extract ATS Keywords from the JD.
Identify ALL important keywords from the JD, including:
- Technical skills and tools (e.g., Flutter, Dart, React.js, REST APIs)
- Methodologies (e.g., Agile, Scrum, CI/CD, TDD)
- Soft skill phrases (e.g., "cross-functional collaboration", "mentoring")
- Domain terms (e.g., "e-commerce", "fintech", "SaaS")
- Action phrases the JD uses repeatedly (e.g., "optimize performance", "scalable solutions")

### Step 2: Check which keywords are MISSING from the resume.
Compare extracted keywords against the resume. Focus on the top 8-12 most critical missing keywords.

### Step 3: Incorporate missing keywords NATURALLY across the resume:
- **Skills section**: Swap out the least relevant skills for the most critical missing JD skills. Keep STRICT domain and category alignment (swap frameworks for frameworks, tools for tools, languages for languages). Ensure the new skill is placed in the logically correct category (e.g., don't put a language in the tools list).
- **Work Experience**: **CRUCIAL**: For EVERY work experience, reword 1 or 2 bullet points to use the JD's exact terminology and explicitly mention using the required skills. Example: resume says "built backend services" and JD says "RESTful APIs" → change to "built RESTful API services using [JD Skill]".
- **Projects**: Same approach — explicitly align project descriptions to use JD terms.
- **Soft Skills**: Replace generic soft skills with JD-specific ones (e.g., "Team Player" → "Cross-functional Collaboration").

### Step 4: Ensure CONSISTENCY.
- Every skill in the Skills section should be mentioned at least once in Experience or Projects.
- The resume should read as ONE cohesive, authentic narrative — not a keyword dump.
- A human recruiter should feel the candidate is a natural fit for the role.

Report all incorporated keywords in the "keywordsAdded" field of your output.`
}


export async function optimizeResume(
  resume: ParsedResume,
  jobDescription: string,
  hardInstructions: string,
  softInstructions: string,
  provider: AIProvider = 'openrouter',
  apiKey?: string,
  model?: string
): Promise<OptimizationResult> {
  const resolvedKey = resolveApiKey(provider, apiKey)

  const prompt = buildPrompt(resume, jobDescription, hardInstructions, softInstructions)
  const responseText = await generateAIResponse({
    provider,
    apiKey: resolvedKey,
    systemInstruction: SYSTEM_INSTRUCTION,
    prompt,
    temperature: 0.2,
    model,
  })
  let raw
  try {
    raw = JSON.parse(responseText)
  } catch {
    // Try to extract/repair JSON from the response (handles markdown fences, truncation, etc.)
    const rescued = extractJSON(responseText)
    if (rescued) {
      try {
        raw = JSON.parse(rescued)
        console.log('[optimizer] Rescued JSON from malformed response')
      } catch {
        // Fall through to error
      }
    }
    if (!raw) {
      console.error('[optimizer] Failed to parse AI response. First 500 chars:', responseText.slice(0, 500))
      throw new Error(`AI returned invalid JSON. This usually means the model's response was truncated. ${invalidJsonHint(provider, model)}`)
    }
  }

  const MAX_CHAR_DIFF = 8 // hard limit — reject changes that exceed this (increased for aggressive ATS rewrites)

  const changes: ResumeChange[] = (raw.changes ?? [])
    .map(
      (c: Omit<ResumeChange, 'id' | 'approved'>, i: number) => ({
        id: `change_${i}_${Date.now()}`,
        sectionId: c.sectionId,
        sectionTitle: c.sectionTitle,
        original: c.original,
        proposed: c.proposed,
        reason: c.reason,
        type: c.type ?? 'rewrite',
        approved: null,
      })
    )
    .filter((c: ResumeChange) => {
      const diff = Math.abs(c.proposed.length - c.original.length)
      if (diff > MAX_CHAR_DIFF) {
        console.warn(
          `[optimizer] Rejected change (±${diff} chars): "${c.original.slice(0, 50)}..." → "${c.proposed.slice(0, 50)}..."`
        )
        return false
      }
      return true
    })


  return {
    summary: raw.summary ?? '',
    companyName: raw.companyName || 'Company',
    keywordsAdded: raw.keywordsAdded ?? [],
    sectionsModified: raw.sectionsModified ?? [],
    changes,
  }
}